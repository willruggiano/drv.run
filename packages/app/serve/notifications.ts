import type { CommitPublication, TaskRecord } from "@earendil-works/pi-durable";
import type { JsonValue } from "@earendil-works/chord";

export type NotificationConfig = {
  activity: ActivityOptions;
  push: PushPolicy | null;
  guests?: RelayPolicy;
};
export class Notifications {
  readonly activity: Activity;
  readonly config: NotificationConfig;
  readonly key: JsonWebKey | undefined;
  private timer?: ReturnType<typeof setTimeout>;
  private stopping = false;
  private delivery?: Promise<void>;
  private readonly releases = new Set<() => void>();
  private readonly send: typeof sendPush;
  private readonly relay?: NotificationRelay;
  constructor(activity: Activity, config: NotificationConfig, key?: JsonWebKey, send = sendPush) {
    this.activity = activity;
    this.config = config;
    this.key = key;
    this.send = send;
    if (config.guests)
      this.relay = new NotificationRelay(activity, config.guests, (error) =>
        console.error("notification relay failed", error),
      );
    if (config.push && !key) throw new Error("Push requires a runtime VAPID key.");
  }
  static async open(directory: string, path: string): Promise<Notifications> {
    const config = object(JSON.parse(await readFile(path, "utf8")) as unknown);
    // Policy is generated by Nix, but malformed operator input still fails closed.
    const a = object(config.activity);
    const options: ActivityOptions = {
      records: numeric(a.records),
      sources: numeric(a.sources),
      history: numeric(a.history),
      retentionDays: numeric(a.retentionDays),
      burst: numeric(a.burst),
      intervalMs: numeric(a.intervalMs),
    };
    let push: PushPolicy | null = null,
      key: JsonWebKey | undefined;
    if (config.push !== null) {
      const p = object(config.push);
      if (
        !Array.isArray(p.origins) ||
        !p.origins.every(
          (origin): origin is string =>
            typeof origin === "string" &&
            new URL(origin).protocol === "https:" &&
            new URL(origin).origin === origin,
        ) ||
        typeof p.subject !== "string" ||
        typeof p.privateKeyFile !== "string" ||
        !p.privateKeyFile.startsWith("/") ||
        p.privateKeyFile.startsWith("/nix/store/")
      )
        throw new TypeError("Invalid push policy.");
      push = { origins: p.origins, subject: p.subject, privateKeyFile: p.privateKeyFile };
      const contact = new URL(push.subject);
      if (contact.protocol !== "mailto:" && contact.protocol !== "https:")
        throw new TypeError("Invalid VAPID subject.");
      key = vapidKey(JSON.parse(await readFile(push.privateKeyFile, "utf8")) as unknown);
    }
    await mkdir(directory, { recursive: true, mode: 0o700 });
    const result = new Notifications(
      new Activity(join(directory, "activity.sqlite"), options),
      {
        activity: options,
        push,
        ...(config.guests == null ? {} : { guests: relayPolicy(config.guests) }),
      },
      key,
    );
    result.start();
    return result;
  }
  start(): void {
    this.relay?.start();
    const tick = () => {
      if (this.stopping) return;
      this.delivery = this.deliver()
        .catch((error: unknown) => console.error("notification delivery failed", error))
        .finally(() => {
          if (!this.stopping) this.timer = setTimeout(tick, 1000);
        });
    };
    tick();
  }
  async close(): Promise<void> {
    this.stopping = true;
    clearTimeout(this.timer);
    for (const release of this.releases) release();
    await this.relay?.close();
    await this.delivery;
    this.activity.close();
  }
  async deliver(): Promise<void> {
    this.activity.prune();
    const id = this.activity.takePending();
    if (id === undefined) return;
    const item = this.activity.history(1, id).find((entry) => entry.id === id);
    if (item?.source.instance.startsWith("drv.run.") && !this.relay?.current(item.source)) {
      this.activity.delivered(id, "disabled");
      this.activity.unavailable(item.source);
      return;
    }
    const { push } = this.config;
    const key = this.key;
    if (!push || !key) {
      this.activity.delivered(id, "disabled");
      return;
    }
    const attempts = this.activity.attempts(id);
    if (attempts > 3) {
      this.activity.delivered(id, "failed");
      return;
    }
    const subscriptions = this.activity.subscriptions().flatMap((value) => {
      try {
        return [pushSubscription(value, push.origins)];
      } catch {
        const data = object(value);
        if (typeof data.endpoint === "string") this.activity.unsubscribe(data.endpoint);
        return [];
      }
    });
    if (!subscriptions.length) {
      this.activity.delivered(id, "disabled");
      return;
    }
    let failed = false,
      succeeded = false;
    await Promise.all(
      subscriptions.map(async (subscription) => {
        try {
          const status = await this.send(subscription, id, push, key);
          if (status === 404 || status === 410) this.activity.unsubscribe(subscription.endpoint);
          else if (status < 200 || status >= 300) failed = true;
          else succeeded = true;
        } catch {
          failed = true;
        }
      }),
    );
    if (failed && attempts < 3) return;
    this.activity.delivered(id, failed ? "failed" : succeeded ? "sent" : "disabled");
  }
  /** Native Durable task events: no terminal, OSC, transcript or model text. */
  async attach(session: Session): Promise<void> {
    const source: ActivitySource = {
      instance: "host-pi",
      incarnation: session.id,
      terminal: "api",
    };
    let sequence = this.activity.sequence(source);
    let ready = false,
      lost = false,
      ended = false;
    const queue: CommitPublication[] = [];
    const drain = () => {
      if (!ready || this.stopping || ended) return;
      try {
        for (const publication of queue.splice(0)) {
          for (const change of publication.changes) {
            if (change.type !== "task" || !observedTask(change.value)) continue;
            this.activity.accept(source, ++sequence, {
              type: "status",
              record: taskStatus(change.value),
            });
          }
        }
        if (lost) this.activity.gap(source);
      } catch (error) {
        this.activity.unavailable(source);
        session.owner.options.onReport?.(error);
      }
    };
    const stop = session.harness.subscribeCommits((publication) => {
      if (
        !publication.changes.some((change) => change.type === "task" && observedTask(change.value))
      )
        return;
      // Do not perform I/O inside Durable's commit observer.
      if (queue.length >= 1024) {
        lost = true;
        return;
      }
      queue.push(publication);
      queueMicrotask(drain);
    });
    const close = session.harness.subscribeClose(() => {
      stop();
      this.releases.delete(release);
      queueMicrotask(() => {
        drain();
        ended = true;
        if (!this.stopping) this.activity.unavailable(source);
      });
    });
    const release = () => {
      ended = true;
      stop();
      close();
    };
    this.releases.add(release);
    try {
      const paused = (await session.harness.inspect(BACKGROUND_CONTEXT)).scheduling === "paused";
      const tasks = await session.harness.commit(async (tx) => {
        const generation = await tx.scanTasks(
          { kind: "pi.generation", order: "descending" },
          this.config.activity.records,
        );
        const compaction = await tx.scanTasks(
          { kind: "pi.compaction", order: "descending" },
          this.config.activity.records,
        );
        return [...generation.items, ...compaction.items]
          .sort((a, b) => b.id - a.id)
          .slice(0, this.config.activity.records);
      }, BACKGROUND_CONTEXT);
      this.activity.accept(source, ++sequence, {
        type: "snapshot",
        records: tasks.map((task) => taskStatus(task, paused)),
      });
      ready = true;
      drain();
    } catch (error) {
      release();
      this.releases.delete(release);
      throw error;
    }
  }
  async route(request: IncomingMessage, response: ServerResponse, url: URL): Promise<void> {
    if (request.method === "GET" && url.pathname === "/activity") {
      response.writeHead(200, {
        "Content-Type": "text/html; charset=utf-8",
        "Cache-Control": "no-store",
      });
      response.end(
        renderHTML(
          h`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Activity · drv.run</title><link rel="stylesheet" href="/styles.css"><link rel="manifest" href="/sessions/manifest.webmanifest"><script type="module" src="/activity-client.js"></script></head><body><main><nav><a href="/sessions">Sessions</a></nav><h1>Activity</h1><p id="connection">Connecting…</p><button id="enable-push" type="button">Enable push on this device</button><button id="disable-push" type="button">Disable push on this device</button><p id="push-status" role="status"></p><h2>Current status</h2><div id="sources"></div><h2>Inbox</h2><div id="inbox"></div></main></body></html>`,
        ),
      );
      return;
    }
    if (request.method === "GET" && url.pathname === "/activity/events") {
      const selected = url.searchParams.has("item")
        ? Number(url.searchParams.get("item"))
        : undefined;
      if (selected !== undefined && (!Number.isSafeInteger(selected) || selected < 1))
        throw new FormError(400, "Invalid activity ID.");
      response.writeHead(200, {
        "Content-Type": "text/event-stream",
        "Cache-Control": "no-store",
        "X-Accel-Buffering": "no",
      });
      const send = () => {
        if (response.destroyed) return;
        if (response.writableLength > 1024 * 1024) {
          response.destroy();
          return;
        }
        response.write(
          `data: ${JSON.stringify({ sources: this.activity.sources(), history: this.activity.history(100, selected), publicKey: this.key ? vapidPublic(this.key) : null })}\n\n`,
        );
      };
      const release = this.activity.watch(send);
      const timer = setInterval(() => {
        if (!response.destroyed) response.write(": keepalive\n\n");
      }, 20_000);
      response.once("close", () => {
        release();
        clearInterval(timer);
      });
      send();
      return;
    }
    if (request.method !== "POST") throw new FormError(405, "Method not allowed.");
    if (
      request.headers.origin !== url.origin ||
      request.headers["content-type"] !== "application/json"
    )
      throw new FormError(403, "Same-origin JSON required.");
    let length = 0;
    const chunks: Buffer[] = [];
    for await (const chunk of request) {
      const bytes = Buffer.from(chunk);
      length += bytes.length;
      if (length > 8192) throw new FormError(413, "Request too large.");
      chunks.push(bytes);
    }
    let input: unknown;
    try {
      input = JSON.parse(Buffer.concat(chunks).toString()) as unknown;
    } catch {
      throw new FormError(400, "Invalid JSON.");
    }
    const data = object(input);
    if (url.pathname === "/activity/read") this.activity.read(numeric(data.id));
    else if (url.pathname === "/activity/subscribe") {
      if (!this.config.push) throw new FormError(409, "Push is disabled by host policy.");
      const subscription = pushSubscription(data, this.config.push.origins);
      await pushTarget(subscription.endpoint, this.config.push.origins);
      this.activity.subscribe(subscription.endpoint, subscription);
    } else if (url.pathname === "/activity/unsubscribe") {
      if (typeof data.endpoint !== "string" || data.endpoint.length > 4096)
        throw new TypeError("Invalid endpoint.");
      this.activity.unsubscribe(data.endpoint);
    } else throw new FormError(404, "Not found.");
    response.writeHead(204);
    response.end();
  }
}
function numeric(value: unknown): number {
  if (typeof value !== "number" || !Number.isSafeInteger(value))
    throw new TypeError("Invalid configuration number.");
  return value;
}
function observedTask(task: TaskRecord<JsonValue, JsonValue, JsonValue>): boolean {
  return task.kind === "pi.generation" || task.kind === "pi.compaction";
}
function taskStatus(
  task: TaskRecord<JsonValue, JsonValue, JsonValue>,
  paused = false,
): ProgramStatus {
  const state =
    task.state.status !== "terminal"
      ? "working"
      : task.state.outcome.status === "completed"
        ? "done"
        : task.state.outcome.status === "aborted"
          ? "idle"
          : "error";
  const record: ProgramStatus = { id: `${task.conversationId}/${task.id}`, state, app: "pi" };
  return paused && state === "working"
    ? { ...record, state: "blocked", kind: "question", msg: "Resume required" }
    : record;
}
